    public static void printNested(ArrayList<?> list) {
        System.out.print("[");

        for (int i = 0; i < list.size(); i++) {
            Object item = list.get(i);

            if (item instanceof String) {
                System.out.print(item);
            } else if (item instanceof ArrayList<?>) {
                printNested((ArrayList<?>) item);
            }

            if (i < list.size() - 1) {
                System.out.print(", ");
            }
        }
        System.out.print("]");
    }

