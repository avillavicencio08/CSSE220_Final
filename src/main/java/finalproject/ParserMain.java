    public static String printFunc(ArrayList<?> list) {
        String func = "(";
        for (int i = 0; i < list.size(); i++) {
            Object item = list.get(i);
            if (item instanceof String) {
                func = func + item;
            } else if (item instanceof ArrayList<?>) {
                func = func+printFunc((ArrayList<?>) item);
            }
        }
        return func + ")";
    }



    public static boolean isDouble(String s) {
        try {
            Double.parseDouble(s);
            return true;
        } catch (NumberFormatException e) {
            return false;
        }
    }
    public static boolean isInteger(String s) {
        try {
            Integer.parseInt(s);
            return true;
        } catch (NumberFormatException e) {
            if (isDouble(s)){
                double n = Double.parseDouble(s);

                return Math.abs(n - Math.floor(n)) <= Math.pow(10.0, -8.0);
            }

            return false;
        }
    }











private ArrayList<Object> funcParse(String func){
        ArrayList<Object> parts = new ArrayList<>();
    String current="";
        boolean searching = true;
        int pDepth = 0;
        int charN =-1;
        int charSave;
        while (searching) {
            charN += 1;
            if (charN >= func.length() - 1) {
                searching = false;

            }

            if (func.charAt(charN) == '(') {
                pDepth += 1;
            } else if (func.charAt(charN) == ')') {


                pDepth -= 1;
            } else if (pDepth == 0) {
                current = current + func.charAt(charN);
                if (!searching && isDouble(current)){
                    parts.add(current);
                    vars.put(current,new Constant(Double.parseDouble(current)));
                    return parts;
                }








                if (twoInputFuncs.containsKey(current)) {
                    searching = false;
                    if (current.equals("LOG")) {
                        charSave = charN + 2;
                        while (func.charAt(charN) != ',') {
                            charN += 1;
                        }



                        return funcParse("(LN(" + func.substring(charSave, charN) + "))/(LN(" + func.substring(charN + 1, func.length() - 1) + "))");
                        //ln/ln
                    } else {
                        parts.add(funcParse(func.substring(1, charN - current.length())));
                        //(goes from the second character, after 1st open paren, to right before the close parenthesis before current symbol
                        parts.add(current);
                        parts.add(funcParse(func.substring(charN + 2, func.length() - 1)));
                        //(goes from the second character after current, after 1st open paren, to right before the close parenthesis at the end , second to last char

                    }
                }
                if (oneInputFuncs.containsKey(current)) {
                    searching = false;
                    parts.add(current);
                    System.out.println(func.substring(charN + 2, func.length() - 1));
                    parts.add(funcParse(func.substring(charN + 2, func.length() - 1)));
                    //(goes from the second character after current, after 1st open paren, to right before the close parenthesis at the end , second to last char

                }
                if (vars.containsKey(current)) {
                    searching = false;
                    parts.add(current);

                }
            }
        }

        return parts;
    }






